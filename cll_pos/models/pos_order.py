class PosOrder(models.Model):
    _inherit = "pos.order"

    purchase_order_count = fields.Integer(
        "Number of Purchase Order Generated",
        compute="_compute_purchase_order_count",
        groups="purchase.group_purchase_user",
    )

    @api.model
    def _get_invoice_lines_values(self, line_values, pos_order_line):
        vals = super()._get_invoice_lines_values(line_values, pos_order_line)
        vals["analytic_distribution"] = pos_order_line.order_id.session_id.config_id.analytic_distribution
        return vals


    @api.depends("lines.purchase_line_ids.order_id")
    def _compute_purchase_order_count(self):
        for order in self:
            order.purchase_order_count = len(order._get_purchase_orders())

    def action_view_purchase_orders(self):
        self.ensure_one()
        purchase_order_ids = self._get_purchase_orders().ids
        action = {
            "res_model": "purchase.order",
            "type": "ir.actions.act_window",
        }
        if len(purchase_order_ids) == 1:
            action.update(
                {
                    "view_mode": "form",
                    "res_id": purchase_order_ids[0],
                }
            )
        else:
            action.update(
                {
                    "name": _("Purchase Order generated from %s", self.name),
                    "domain": [("id", "in", purchase_order_ids)],
                    "view_mode": "list,form",
                }
            )
        return action

    def action_open_pos_order_layout(self):
        return {
            'type': 'ir.actions.act_window',
            'res_model': 'pos.order.product',  # This should be the wizard model
            'view_mode': 'form',
            'target': 'new',
        }

    def _get_purchase_orders(self):
        return self.lines.purchase_line_ids.order_id



class PosOrderLine(models.Model):
    _inherit = "pos.order.line"

    purchase_line_ids = fields.One2many(
        "purchase.order.line",
        "pos_line_id",
        string="Generated Purchase Lines",
        readonly=True,
        help="Purchase line generated by this Sales item on order confirmation, or when the quantity was increased.",
    )
    purchase_line_count = fields.Integer(
        "Number of generated purchase items", compute="_compute_purchase_count"
    )
    to_print = fields.Boolean(string="To Print")

    @api.depends("purchase_line_ids")
    def _compute_purchase_count(self):
        database_data = (
            self.env["purchase.order.line"]
            .sudo()
            ._read_group(
                [("pos_line_id", "in", self.ids)], ["pos_line_id"], ["__count"]
            )
        )
        mapped_data = {pos_line.id: count for pos_line, count in database_data}
        for line in self:
            line.purchase_line_count = mapped_data.get(line.id, 0)

    def _purchase_service_generation(self):
        """Create a Purchase for the first time from the sale line. If the SO line already created a PO, it
        will not create a second one.
        """
        sale_line_purchase_map = {}
        for line in self.filtered(lambda pos: not pos.order_id.refunded_order_id):
            # Do not regenerate PO line if the SO line has already created one in the past (SO cancel/reconfirmation case)
            if (
                line.product_id.service_to_purchase
                and not line.purchase_line_count
                and line.qty > 0
            ):
                result = line._purchase_service_create()
                sale_line_purchase_map.update(result)
        return sale_line_purchase_map

    def _retrieve_purchase_partner(self):
        """In case we want to explicitely name a partner from whom we want to buy or receive products"""
        self.ensure_one()
        return False

    def _purchase_service_match_supplier(self, warning=True):
        # determine vendor of the order (take the first matching company and product)
        suppliers = self.product_id._select_seller(
            partner_id=self._retrieve_purchase_partner(),
            quantity=abs(self.qty),
            uom_id=self.product_uom_id,
        )
        if warning and not suppliers:
            raise UserError(
                _(
                    "There is no vendor associated to the product %s. Please define a vendor for this product.",
                    self.product_id.display_name,
                )
            )
        return suppliers[0]

    def _purchase_get_date_order(self, supplierinfo):
        """return the ordered date for the purchase order, computed as : SO commitment date - supplier delay"""
        commitment_date = fields.Datetime.from_string(
            self.order_id.date_order or fields.Datetime.now()
        )
        return commitment_date - relativedelta(days=int(supplierinfo.delay))

    def _purchase_service_get_company(self):
        return self.company_id

    def _purchase_service_prepare_order_values(self, supplierinfo):
        """Returns the values to create the purchase order from the current SO line.
        :param supplierinfo: record of product.supplierinfo
        :rtype: dict
        """
        self.ensure_one()
        partner_supplier = supplierinfo.partner_id
        fpos = (
            self.env["account.fiscal.position"]
            .sudo()
            ._get_fiscal_position(partner_supplier)
        )
        date_order = self._purchase_get_date_order(supplierinfo)
        return {
            "partner_id": partner_supplier.id,
            "partner_ref": partner_supplier.ref,
            "company_id": self._purchase_service_get_company().id,
            "currency_id": partner_supplier.property_purchase_currency_id.id
            or self.env.company.currency_id.id,
            "dest_address_id": False,  # False since only supported in stock
            "origin": self.order_id.name,
            "payment_term_id": partner_supplier.property_supplier_payment_term_id.id,
            "date_order": date_order,
            "fiscal_position_id": fpos.id,
        }

    def _purchase_service_match_purchase_order(self, partner, company=False):
        return self.env["purchase.order"].search(
            [
                ("partner_id", "=", partner.id),
                ("state", "=", "draft"),
                ("company_id", "=", (company and company or self.env.company).id),
            ],
            order="id desc",
        )

    def _create_purchase_order(self, supplierinfo):
        values = self._purchase_service_prepare_order_values(supplierinfo)
        return (
            self.env["purchase.order"]
            .with_context(mail_create_nosubscribe=True)
            .create(values)
        )

